// Optional browser checks: install Playwright separately, start npm start, then run this file.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {mkdir}=require('node:fs/promises');
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const base=process.env.PREVIEW_URL||'http://127.0.0.1:4173/';
  await mkdir('/tmp/zhizhi-qa',{recursive:true});
  assert.equal((await page.goto(base)).status(),200);
  await page.waitForSelector('.branch-card');
  assert.equal(await page.locator('.branch-card').count(),10);
  const count=await page.locator('.leaf').count();assert(count>=45);
  await page.screenshot({path:'/tmp/zhizhi-qa/desktop.png',fullPage:true});
  await page.locator('#search-open').click();
  await page.locator('#search-input').fill('RAG');
  await page.locator('[data-search-node="rag-intro"]').click();
  assert.equal(await page.locator('#reader h2').textContent(),'检索增强生成');
  await page.locator('#bookmark-node').click();
  await page.locator('[data-answer="0"]').click();
  assert.match(await page.locator('#quiz-feedback').textContent(),/再想/);
  await page.locator('[data-answer="1"]').click();
  assert.match(await page.locator('#reader-status').textContent(),/自测通过/);
  await page.screenshot({path:'/tmp/zhizhi-qa/reader.png',fullPage:true});
  await page.keyboard.press('Escape');
  await page.reload();
  await page.locator('[data-view="review"]').click();
  assert.equal(await page.locator('#review-content [data-node="rag-intro"]').count(),1);
  await page.locator('[data-view="routes"]').click();
  await page.locator('[data-route="knowledge"]').click();
  assert.match(await page.locator('#reader h2').textContent(),/上下文工程/);
  await page.locator('#reader-close').click();
  assert.equal(await page.locator('#route-banner').isVisible(),true);
  await page.locator('#route-clear').click();
  await page.locator('#list-view').click();
  assert.equal(await page.locator('#list-content .list-card').count(),count);
  await page.locator('#tree-view').click();
  await page.locator('#start-learning').click();
  assert.equal(await page.locator('#reader h2').textContent(),'词元与词元化');
  await page.locator('#reader-close').click();
  const zoom=await page.locator('#zoom-label').textContent();
  await page.locator('#zoom-in').click();
  assert.notEqual(await page.locator('#zoom-label').textContent(),zoom);
  await page.locator('#fit-map').click();
  const downloadPromise=page.waitForEvent('download');await page.locator('#export-progress').click();const download=await downloadPromise;
  await download.saveAs('/tmp/zhizhi-qa/progress.json');
  await page.locator('#import-file').setInputFiles('/tmp/zhizhi-qa/progress.json');
  assert.match(await page.locator('#toast').textContent(),/合并/);
  for(const width of [360,390,768,1024,1440]){
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`horizontal overflow at ${width}`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/zhizhi-qa/mobile.png',fullPage:true});
  await page.locator('#search-open').click();await page.locator('#search-input').fill('token');await page.locator('[data-search-node="token"]').click();
  assert.equal(await page.locator('#reader').isVisible(),true);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'reader horizontal overflow');
  await page.screenshot({path:'/tmp/zhizhi-qa/mobile-reader.png',fullPage:true});
  await page.locator('#reader-close').click();
  await page.goto(base+'#node/retry');
  assert.equal(await page.locator('#reader h2').textContent(),'重试与幂等');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({nodes:count,branches:10,search:'passed',quiz:'passed',persistence:'passed',bookmarks:'passed',routes:'passed',list:'passed',zoom:'passed',importExport:'passed',deepLink:'passed',responsive:[360,390,768,1024,1440],runtimeErrors:errors},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
